    public void carregarTarefas() {
        DefaultListModel modelo = new DefaultListModel();
        modelo.removeAllElements();

        for (Tarefa c : listaTarefas) {
            modelo.addElement(c);
        }

        lstTarefas.setModel(modelo);
    }

