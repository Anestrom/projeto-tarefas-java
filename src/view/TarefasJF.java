    private void btnAdcionarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAdcionarActionPerformed
        CadastroTarefaJD telaCadastro = new CadastroTarefaJD(this, true);
        telaCadastro.setVisible(true);

        Tarefa tarefaNova = telaCadastro.getTarefa();

        if (tarefaNova != null) {
            TarefasController control = new TarefasController();
            listaTarefas = (ArrayList<Tarefa>) control.addTarefa(tarefaNova, listaTarefas);
            carregarTarefas();
        }
    }//GEN-LAST:event_btnAdcionarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        Tarefa tarefaSelecionada = lstTarefas.getSelectedValue();

        if (tarefaSelecionada != null) {
            CadastroTarefaJD telaCadastro = new CadastroTarefaJD(this, true);
            telaCadastro.setTarefa(tarefaSelecionada);

            telaCadastro.setVisible(true);

            carregarTarefas();
        } else {
            JOptionPane.showMessageDialog(rootPane, "Selecione uma tarefa para editar!");
        }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnRemoverActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRemoverActionPerformed
        Tarefa tarefaSelecionada = lstTarefas.getSelectedValue();
        if (tarefaSelecionada != null) {
            int opRemover = JOptionPane.showConfirmDialog(rootPane, "Tem certeza que deseja remover a Tarefa " + tarefaSelecionada.getNome() + "?");

            if (opRemover == JOptionPane.YES_OPTION) {
                listaTarefas.remove(tarefaSelecionada);
                carregarTarefas();
            }
        } else {
            JOptionPane.showMessageDialog(rootPane, "Selecione uma Tarefa para remover!");
        }
    }//GEN-LAST:event_btnRemoverActionPerformed

